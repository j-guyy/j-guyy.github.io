#!/usr/bin/env python3
"""Build data/hunter-names.json: id -> name for every Strava hunter.

Also writes data/ecoregion-names.json, just the ecoregion part (Level III
name + biome, Level IV name + Level III), for the US Travel page's
Ecoregions table, which shouldn't download the whole lookup.

The hunters save only ids to the worker (county FIPS codes, park and metro
slugs, ecoregion codes, pass ids). Their names sit in boundary files of several
MB each, too big for the worker to load per request, so the worker's MCP
endpoint (/mcp) fetches this small lookup instead.

Re-run whenever one of the source files below changes:

    python3 scripts/build-hunter-names.py

Standard library only. TopoJSON properties are read straight from the file;
no geometry is decoded.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'data'
OUT = DATA / 'hunter-names.json'
ECO_OUT = DATA / 'ecoregion-names.json'

STATE_BY_FIPS = {
    '01': 'AL', '02': 'AK', '04': 'AZ', '05': 'AR', '06': 'CA', '08': 'CO', '09': 'CT',
    '10': 'DE', '11': 'DC', '12': 'FL', '13': 'GA', '15': 'HI', '16': 'ID', '17': 'IL',
    '18': 'IN', '19': 'IA', '20': 'KS', '21': 'KY', '22': 'LA', '23': 'ME', '24': 'MD',
    '25': 'MA', '26': 'MI', '27': 'MN', '28': 'MS', '29': 'MO', '30': 'MT', '31': 'NE',
    '32': 'NV', '33': 'NH', '34': 'NJ', '35': 'NM', '36': 'NY', '37': 'NC', '38': 'ND',
    '39': 'OH', '40': 'OK', '41': 'OR', '42': 'PA', '44': 'RI', '45': 'SC', '46': 'SD',
    '47': 'TN', '48': 'TX', '49': 'UT', '50': 'VT', '51': 'VA', '53': 'WA', '54': 'WV',
    '55': 'WI', '56': 'WY', '72': 'PR',
}

# Census LSAD code -> the word after the name ("Boulder County", "Orleans Parish").
COUNTY_SUFFIX = {
    '03': 'City and Borough', '04': 'Borough', '05': 'Census Area', '06': 'County',
    '12': 'Municipality', '13': 'Municipio', '15': 'Parish', '25': 'city',
}


def features(name):
    return json.loads((DATA / name).read_text(encoding='utf-8'))['features']


def counties():
    out = {}
    for f in features('counties-us.json'):
        p = f['properties']
        suffix = COUNTY_SUFFIX.get(p['LSAD'])
        name = f"{p['NAME']} {suffix}" if suffix else p['NAME']
        out[p['GEOID']] = [name, STATE_BY_FIPS.get(p['STATEFP'], '')]
    return out


def ecoregions():
    l4, l3, biome = {}, {}, {}
    topo = json.loads((DATA / 'us-ecoregions.topojson').read_text(encoding='utf-8'))
    props = [g['properties'] for obj in topo['objects'].values() for g in obj['geometries']]
    props += [f['properties'] for f in features('ak-ecoregions.geojson')]
    for p in props:
        l4.setdefault(p['US_L4CODE'], [p['US_L4NAME'], p['US_L3CODE']])
        l3.setdefault(p['US_L3CODE'], p['US_L3NAME'])
        biome.setdefault(p['US_L3CODE'], p['NA_L1NAME'].title())
    return l4, l3, biome


def main():
    l4, l3, biome = ecoregions()
    passes = json.loads((DATA / 'colorado-passes.json').read_text(encoding='utf-8'))['passes']
    out = {
        '_comment': 'Generated by scripts/build-hunter-names.py from the hunter boundary files; '
                    'do not edit by hand. Read by the worker\'s /mcp endpoint.',
        'counties': counties(),
        'parks': {f['properties']['id']: [f['properties']['name'], f['properties'].get('type', '')]
                  for f in features('federal-lands.geojson')},
        'stateParks': {f['properties']['id']: [f['properties']['name'], f['properties'].get('state', '')]
                       for f in features('state-parks.geojson')},
        'metros': {f['properties']['id']: [f['properties']['name'], f['properties'].get('state', ''),
                                           f['properties'].get('rank')]
                   for f in features('metro-areas.geojson')},
        'ecoregions': l4,
        'ecoL3': l3,
        'passes': {p['id']: [p['name'], p.get('ele')] for p in passes},
    }
    OUT.write_text(json.dumps(out, ensure_ascii=False, separators=(',', ':')) + '\n', encoding='utf-8')
    counts = ', '.join(f'{k} {len(v)}' for k, v in out.items() if isinstance(v, dict))
    print(f'Wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB): {counts}')

    eco = {
        '_comment': 'Generated by scripts/build-hunter-names.py; do not edit by hand. '
                    'Read by the US Travel Ecoregions table (js/dashboard.js).',
        'l3': {code: [name, biome[code]] for code, name in sorted(l3.items(), key=lambda kv: int(kv[0]))},
        'l4': l4,
    }
    ECO_OUT.write_text(json.dumps(eco, ensure_ascii=False, separators=(',', ':')) + '\n', encoding='utf-8')
    print(f'Wrote {ECO_OUT.relative_to(ROOT)} ({ECO_OUT.stat().st_size // 1024} KB)')


if __name__ == '__main__':
    main()
